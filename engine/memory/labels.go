package memory

import "strings"

// 18 类通用标签。演示版只保留判定最简单的 12 类，词表匹配、不是理解。
var tagWords = map[string][]string{
	"family":     {"妈", "爸", "父母", "家里", "女儿", "儿子", "家人", "亲戚"},
	"health":     {"病", "住院", "医院", "药", "疼", "血压", "发烧", "失眠", "体检"},
	"work":       {"工作", "上班", "公司", "同事", "老板", "加班", "项目", "客户"},
	"study":      {"学习", "考试", "作业", "老师", "课程", "复习", "论文"},
	"emotion":    {"难过", "开心", "焦虑", "害怕", "孤独", "生气", "委屈", "喜欢"},
	"relation":   {"朋友", "女朋友", "男朋友", "对象", "吵架", "道歉", "约定"},
	"preference": {"喜欢", "讨厌", "爱吃", "不吃", "习惯", "偏爱"},
	"plan":       {"打算", "计划", "准备", "下周", "明天", "以后", "目标"},
	"money":      {"钱", "工资", "花销", "省钱", "贵", "便宜", "预算"},
	"place":      {"家", "学校", "公司", "城市", "搬", "去", "回"},
	"food":       {"吃", "饭", "咖啡", "茶", "面包", "火锅", "早餐"},
	"pet":        {"猫", "狗", "宠物", "养"},
}

// Tag 返回命中的标签 key。纯词表匹配，认得出「住院」，认不出「他说得轻描淡写」。
func Tag(text string) []string {
	out := make([]string, 0, 3)
	for key, words := range tagWords {
		for _, w := range words {
			if strings.Contains(text, w) {
				out = append(out, key)
				break
			}
		}
	}
	return out
}
